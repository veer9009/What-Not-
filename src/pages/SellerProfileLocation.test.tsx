import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, expect, it, vi } from 'vitest';
import App from '../App';
import { setAccessToken } from '../api/client';
const shop={id:2,user_id:1,shop_name:'Maker',phone:'100',description:null,latitude:'19',longitude:'72',is_verified:false,dispatch_location_confirmed_at:null};
afterEach(()=>{setAccessToken(null);vi.unstubAllGlobals();});
it('saves GPS only after explicit dispatch confirmation, without copying to public discovery',async()=>{
  let success!:PositionCallback;
  vi.stubGlobal('navigator',{geolocation:{getCurrentPosition:(cb:PositionCallback)=>{success=cb;}}});
  setAccessToken('test-only');
  const writes=vi.fn();
  vi.stubGlobal('fetch',vi.fn(async(url:string,options:RequestInit)=>{
    const path=new URL(url,location.origin).pathname;
    if(options.method!=='GET')writes(path,JSON.parse(String(options.body)));
    return new Response(JSON.stringify(path.endsWith('/auth/me')?{id:1,name:'Maker',email:'maker@example.test',role:'SELLER'}:shop));
  }));
  render(<MemoryRouter initialEntries={['/seller/profile']}><App/></MemoryRouter>);
  await screen.findByRole('button',{name:'Save profile'});
  expect(screen.queryByLabelText('Latitude')).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('button',{name:'Use Current Location'}));
  await act(async()=>success({coords:{latitude:12.12345678,longitude:-45.12345678,accuracy:10}} as GeolocationPosition));
  expect(writes).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('checkbox',{name:/I confirm this is where I send products from/i}));
  fireEvent.click(screen.getByRole('button',{name:'Save profile'}));
  await waitFor(()=>expect(writes).toHaveBeenCalledWith('/api/v1/sellers/me/dispatch-location',{latitude:12.123457,longitude:-45.123457}));
  expect(writes.mock.calls.some(([path])=>path.endsWith('/public-discovery-location'))).toBe(false);
});
