import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, expect, it, vi } from 'vitest';
import { AddressPage } from './AddressPage';
import { addressesApi } from '../api/addresses';
import type { Address } from '../api/types';
vi.mock('../state/AuthContext',()=>({useAuth:()=>({user:{id:'1',role:'BUYER',name:'Buyer'},logout:vi.fn()})}));
const address:Address={id:'4',user_id:'1',label:'Home',address_line1:'Maker Lane',address_line2:null,city:'Mumbai',state:'Maharashtra',pincode:'400001',latitude:'19',longitude:'72',is_default:false};
afterEach(()=>{vi.restoreAllMocks();vi.unstubAllGlobals();});
it('preserves the saved point on label edits and does not expose coordinates',async()=>{
  vi.spyOn(addressesApi,'list').mockResolvedValue([address]);
  const update=vi.spyOn(addressesApi,'update').mockResolvedValue(address);
  render(<MemoryRouter><AddressPage/></MemoryRouter>);
  fireEvent.click(await screen.findByRole('button',{name:'Edit address'}));
  expect(screen.queryByLabelText('Latitude')).not.toBeInTheDocument();
  fireEvent.change(screen.getByLabelText('Label'),{target:{value:'New label'}});
  fireEvent.click(screen.getByRole('button',{name:'Save address'}));
  await waitFor(()=>expect(update).toHaveBeenCalledWith('4',{label:'New label'}));
});
it('requires GPS for a new address and ignores a cancelled late result',async()=>{
  let success!:PositionCallback;
  vi.stubGlobal('navigator',{geolocation:{getCurrentPosition:(cb:PositionCallback)=>{success=cb;}}});
  vi.spyOn(addressesApi,'list').mockResolvedValue([]);
  const create=vi.spyOn(addressesApi,'create').mockResolvedValue(address);
  render(<MemoryRouter><AddressPage/></MemoryRouter>);
  fireEvent.click(await screen.findByRole('button',{name:'Add address'}));
  fireEvent.click(screen.getByRole('button',{name:'Use Current Location'}));
  fireEvent.click(screen.getByRole('button',{name:'Cancel location request'}));
  await act(async()=>success({coords:{latitude:19,longitude:72,accuracy:20}} as GeolocationPosition));
  fireEvent.submit(screen.getByRole('button',{name:'Save address'}).closest('form')!);
  expect(screen.getByRole('alert')).toHaveTextContent(/use current location/i);
  expect(create).not.toHaveBeenCalled();
});
it('saves a GPS point only after the postal fields are entered and the user saves',async()=>{
  vi.stubGlobal('navigator',{geolocation:{getCurrentPosition:(cb:PositionCallback)=>cb({coords:{latitude:12.12345678,longitude:-45.12345678,accuracy:25}} as GeolocationPosition)}});
  vi.spyOn(addressesApi,'list').mockResolvedValue([]);
  const create=vi.spyOn(addressesApi,'create').mockResolvedValue(address);
  render(<MemoryRouter><AddressPage/></MemoryRouter>);
  fireEvent.click(await screen.findByRole('button',{name:'Add address'}));
  fireEvent.click(screen.getByRole('button',{name:'Use Current Location'}));
  await screen.findByText(/location detected/i);
  expect(create).not.toHaveBeenCalled();
  for(const [label,value] of [['Label','Home'],['Address line 1','Maker Lane'],['City','Mumbai'],['State','Maharashtra'],['PIN code','400001']])fireEvent.change(screen.getByLabelText(label),{target:{value}});
  fireEvent.click(screen.getByRole('checkbox',{name:/confirm.*delivery location matches/i}));
  fireEvent.click(screen.getByRole('button',{name:'Save address'}));
  await waitFor(()=>expect(create).toHaveBeenCalledWith(expect.objectContaining({latitude:'12.123457',longitude:'-45.123457',pincode:'400001'})));
});
it('preserves the existing point if permission is denied',async()=>{
  vi.stubGlobal('navigator',{geolocation:{getCurrentPosition:(_cb:PositionCallback,fail:PositionErrorCallback)=>fail({code:1} as GeolocationPositionError)}});
  vi.spyOn(addressesApi,'list').mockResolvedValue([address]);
  const update=vi.spyOn(addressesApi,'update').mockResolvedValue(address);
  render(<MemoryRouter><AddressPage/></MemoryRouter>);
  fireEvent.click(await screen.findByRole('button',{name:'Edit address'}));
  fireEvent.click(screen.getByRole('button',{name:'Use Current Location'}));
  expect(await screen.findByRole('alert')).toHaveTextContent(/permission was denied/i);
  fireEvent.change(screen.getByLabelText('Label'),{target:{value:'Work'}});
  fireEvent.click(screen.getByRole('button',{name:'Save address'}));
  await waitFor(()=>expect(update).toHaveBeenCalledWith('4',{label:'Work'}));
});
it('requires renewed confirmation when postal details change and clears confirmation on another edit',async()=>{
  vi.spyOn(addressesApi,'list').mockResolvedValue([address]);
  const update=vi.spyOn(addressesApi,'update').mockResolvedValue(address);
  render(<MemoryRouter><AddressPage/></MemoryRouter>);
  fireEvent.click(await screen.findByRole('button',{name:'Edit address'}));
  fireEvent.change(screen.getByLabelText('Address line 1'),{target:{value:'New lane'}});
  fireEvent.click(screen.getByRole('button',{name:'Save address'}));
  expect(update).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('checkbox',{name:/confirm.*delivery location matches/i}));
  fireEvent.change(screen.getByLabelText('City'),{target:{value:'Pune'}});
  expect(screen.getByRole('checkbox',{name:/confirm.*delivery location matches/i})).not.toBeChecked();
  fireEvent.click(screen.getByRole('checkbox',{name:/confirm.*delivery location matches/i}));
  fireEvent.click(screen.getByRole('button',{name:'Save address'}));
  await waitFor(()=>expect(update).toHaveBeenCalledWith('4',{address_line1:'New lane',city:'Pune'}));
});
it('ignores a GPS result after the postal address is edited',async()=>{
  let success!:PositionCallback;
  vi.stubGlobal('navigator',{geolocation:{getCurrentPosition:(cb:PositionCallback)=>{success=cb;}}});
  vi.spyOn(addressesApi,'list').mockResolvedValue([address]);
  const update=vi.spyOn(addressesApi,'update').mockResolvedValue(address);
  render(<MemoryRouter><AddressPage/></MemoryRouter>);
  fireEvent.click(await screen.findByRole('button',{name:'Edit address'}));
  fireEvent.click(screen.getByRole('button',{name:'Use Current Location'}));
  fireEvent.change(screen.getByLabelText('City'),{target:{value:'Pune'}});
  await act(async()=>success({coords:{latitude:21,longitude:73,accuracy:20}} as GeolocationPosition));
  fireEvent.click(screen.getByRole('checkbox',{name:/confirm.*delivery location matches/i}));
  fireEvent.click(screen.getByRole('button',{name:'Save address'}));
  await waitFor(()=>expect(update).toHaveBeenCalledWith('4',{city:'Pune'}));
});
